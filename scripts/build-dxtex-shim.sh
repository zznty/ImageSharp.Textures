#!/usr/bin/env bash
#
# Build the in-process DirectXTex codec shim used by the benchmark baseline.
#
#   scripts/build-dxtex-shim.sh [--force]
#
# Produces: artifacts/dxtexshim/libdxtexshim.so
#
# The shim is a thin `extern "C"` wrapper over the DirectXTex CPU block codecs
# (`D3DXDecodeBC1/BC4U/BC5U/BC7`, `D3DXEncodeBC1/BC4U/BC5U/BC7`) operating on raw
# buffers: no COM, no device and no DDS parsing. It links the same `libDirectXTex.a`
# that `scripts/build-texconv.sh` produces, so the benchmark compares our codecs with
# the pinned DirectXTex source (232bbf2e) and not with a separately configured build.
#
# Exports:
#   int  dxtex_block_bytes(int format)                0=BC1 1=BC4 2=BC5 3=BC7
#   void dxtex_decode(int format, const uint8_t* src, uint8_t* rgba, int width, int height)
#   void dxtex_encode(int format, const uint8_t* rgba, uint8_t* dst, int width, int height,
#                     int quality, float bc1_alpha_threshold)
#
# quality: 0 = BC7 mode 6 only (BC_FLAGS_FORCE_BC7_MODE6), 1 = DirectXTex default search.
# BC1 uses `bc1_alpha_threshold` as its punch-through threshold; the other formats ignore it.

set -euo pipefail

TEXCONV_COMMIT="40b28a07e760a145e8677fb65b5e1ffb7e712e48" # v0.6.0
DIRECTXTEX_COMMIT="232bbf2e39a37ea2e9b7b8331653fa69bd4797a2"

step() { printf '\n==> %s\n' "$*"; }
info() { printf '    %s\n' "$*"; }
die() {
    printf '\nERROR: %s\n' "$*" >&2
    exit 1
}

FORCE=0
for arg in "$@"; do
    case "$arg" in
        --force) FORCE=1 ;;
        -h | --help)
            sed -n '2,26p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *) die "unknown argument: $arg (expected --force)" ;;
    esac
done

# Resolve the repository root from this script's location, independent of cwd.
SCRIPT_PATH="${BASH_SOURCE[0]}"
while [ -L "$SCRIPT_PATH" ]; do
    link_target="$(readlink "$SCRIPT_PATH")"
    case "$link_target" in
        /*) SCRIPT_PATH="$link_target" ;;
        *) SCRIPT_PATH="$(dirname "$SCRIPT_PATH")/$link_target" ;;
    esac
done
SCRIPT_DIR="$(cd -P "$(dirname "$SCRIPT_PATH")" && pwd)"
REPO_ROOT="$(cd -P "$SCRIPT_DIR/.." && pwd)"

CHECKOUT_DIR="$REPO_ROOT/artifacts/texconv"
DIRECTXTEX_DIR="$CHECKOUT_DIR/DirectXTex"
STATIC_LIB="$CHECKOUT_DIR/build/lib/libDirectXTex.a"
OUT_DIR="$REPO_ROOT/artifacts/dxtexshim"
OUT_LIB="$OUT_DIR/libdxtexshim.so"
SHIM_SRC="$OUT_DIR/dxtex_shim.cpp"

for tool in g++ nm; do
    command -v "$tool" >/dev/null 2>&1 || die "required tool not found: $tool"
done

step "Repository root: $REPO_ROOT"

# ---------------------------------------------------------------- pinned checkout
[ -d "$DIRECTXTEX_DIR" ] || die "DirectXTex checkout missing: $DIRECTXTEX_DIR (run scripts/build-texconv.sh)"
if git -C "$CHECKOUT_DIR" rev-parse --git-dir >/dev/null 2>&1; then
    TEXCONV_SHA="$(git -C "$CHECKOUT_DIR" rev-parse HEAD)"
    [ "$TEXCONV_SHA" = "$TEXCONV_COMMIT" ] ||
        die "Texconv-Custom-DLL HEAD is $TEXCONV_SHA, expected $TEXCONV_COMMIT"
    info "Texconv-Custom-DLL HEAD: $TEXCONV_SHA"

    DIRECTXTEX_SHA="$(git -C "$DIRECTXTEX_DIR" rev-parse HEAD)"
    [ "$DIRECTXTEX_SHA" = "$DIRECTXTEX_COMMIT" ] ||
        die "DirectXTex HEAD is $DIRECTXTEX_SHA, expected $DIRECTXTEX_COMMIT"
    info "DirectXTex HEAD: $DIRECTXTEX_SHA"
else
    info "no git metadata in $CHECKOUT_DIR; skipping the commit pins"
fi

# ------------------------------------------------------------- static DirectXTex
if [ ! -f "$STATIC_LIB" ]; then
    step "libDirectXTex.a missing; building the DirectXTex library (Release, no OpenMP, PIC)"
    for tool in cmake ninja; do
        command -v "$tool" >/dev/null 2>&1 || die "required tool not found: $tool"
    done
    (
        cd "$CHECKOUT_DIR"
        cmake -G Ninja -S . -B build \
            -DCMAKE_BUILD_TYPE=Release \
            -DTEXCONV_BUILD_AS_EXE=ON \
            -DTEXCONV_USE_TEXASSEMBLE=OFF \
            -DBC_USE_OPENMP=OFF \
            -DCMAKE_POSITION_INDEPENDENT_CODE=ON
        cmake --build build --target DirectXTex
    )
    [ -f "$STATIC_LIB" ] || die "expected static library not found: $STATIC_LIB"
fi
info "static library: $STATIC_LIB"

if [ "$FORCE" -eq 0 ] && [ -f "$OUT_LIB" ] && [ "$OUT_LIB" -nt "$STATIC_LIB" ]; then
    info "reusing up-to-date $OUT_LIB (pass --force to rebuild)"
else
    step "Writing the shim translation unit"
    mkdir -p "$OUT_DIR"
    cat >"$SHIM_SRC" <<'SOURCE'
// Generated by scripts/build-dxtex-shim.sh - do not edit.
//
// Thin `extern "C"` surface over the DirectXTex CPU block codecs for the benchmark baseline.
// Buffers are raw: the block payloads and RGBA32 surfaces are supplied by the caller, so the
// measurement contains the codec and nothing else (no COM, no device, no DDS/TGA parsing).

#include <algorithm>
#include <cstdint>
#include <cstring>

#include "BC.h"

using namespace DirectX;

namespace {

constexpr int MaxPixels = 16;

// DirectXTex's own byte -> unit conversion (XMLoadUByteN4 multiplies by 1/255 rather than dividing).
inline float ToUnit(uint8_t value) noexcept
{
    return static_cast<float>(value) * (1.0f / 255.0f);
}

// DirectXTex's LDRColorA(const HDRColorA&) conversion: clamp to [0, 1], scale, truncate with a bias.
inline uint8_t ToByte(float value) noexcept
{
    const float clamped = std::min(1.0f, std::max(0.0f, value)) * 255.0f;
    return static_cast<uint8_t>(clamped + 0.001f);
}

} // namespace

extern "C" {

int dxtex_block_bytes(int format)
{
    switch (format)
    {
        case 0: return 8;   // BC1
        case 1: return 8;   // BC4
        case 2: return 16;  // BC5
        case 3: return 16;  // BC7
        default: return 0;
    }
}

void dxtex_decode(int format, const uint8_t* src, uint8_t* rgba, int width, int height)
{
    const int blockBytes = dxtex_block_bytes(format);
    const int blockColumns = (width + 3) >> 2;
    const int blockRows = (height + 3) >> 2;

    alignas(16) XMVECTOR colors[MaxPixels];

    for (int by = 0; by < blockRows; ++by)
    {
        for (int bx = 0; bx < blockColumns; ++bx)
        {
            const uint8_t* block = src + (static_cast<size_t>(by) * blockColumns + bx) * blockBytes;

            switch (format)
            {
                // D3DXDecodeBC1 is the punch-through-aware decoder; DirectXTex has no separate no-alpha variant.
                case 0: D3DXDecodeBC1(colors, block); break;
                case 1: D3DXDecodeBC4U(colors, block); break;
                case 2: D3DXDecodeBC5U(colors, block); break;
                default: D3DXDecodeBC7(colors, block); break;
            }

            for (int t = 0; t < 4; ++t)
            {
                const int y = (by << 2) + t;
                if (y >= height)
                {
                    break;
                }

                for (int s = 0; s < 4; ++s)
                {
                    const int x = (bx << 2) + s;
                    if (x >= width)
                    {
                        break;
                    }

                    alignas(16) float pixel[4];
                    XMStoreFloat4(reinterpret_cast<XMFLOAT4*>(pixel), colors[(t << 2) + s]);

                    uint8_t* out = rgba + (static_cast<size_t>(y) * width + x) * 4;
                    out[0] = ToByte(pixel[0]);
                    out[1] = ToByte(pixel[1]);
                    out[2] = ToByte(pixel[2]);
                    out[3] = ToByte(pixel[3]);
                }
            }
        }
    }
}

void dxtex_encode(int format, const uint8_t* rgba, uint8_t* dst, int width, int height, int quality, float bc1_alpha_threshold)
{
    const int blockBytes = dxtex_block_bytes(format);
    const int blockColumns = (width + 3) >> 2;
    const int blockRows = (height + 3) >> 2;
    const uint32_t flags = (quality == 0) ? BC_FLAGS_FORCE_BC7_MODE6 : BC_FLAGS_NONE;

    alignas(16) XMVECTOR texels[MaxPixels];

    // The partial-block fill map from CompressBC: missing columns and rows reuse texels 0, 0 and 1.
    static const size_t sourceIndex[4] = { 0, 0, 0, 1 };

    for (int by = 0; by < blockRows; ++by)
    {
        for (int bx = 0; bx < blockColumns; ++bx)
        {
            const int x0 = bx << 2;
            const int y0 = by << 2;
            const int pw = std::min(4, width - x0);
            const int ph = std::min(4, height - y0);

            for (int i = 0; i < MaxPixels; ++i)
            {
                texels[i] = XMVectorZero();
            }

            for (int t = 0; t < ph; ++t)
            {
                for (int s = 0; s < pw; ++s)
                {
                    const uint8_t* in = rgba + (static_cast<size_t>(y0 + t) * width + x0 + s) * 4;
                    texels[(t << 2) + s] = XMVectorSet(ToUnit(in[0]), ToUnit(in[1]), ToUnit(in[2]), ToUnit(in[3]));
                }
            }

            if (pw != 4)
            {
                for (int t = 0; t < ph; ++t)
                {
                    for (int s = pw; s < 4; ++s)
                    {
                        texels[(t << 2) + s] = texels[(t << 2) + sourceIndex[s]];
                    }
                }
            }

            if (ph != 4)
            {
                for (int t = ph; t < 4; ++t)
                {
                    for (int s = 0; s < 4; ++s)
                    {
                        texels[(t << 2) + s] = texels[(sourceIndex[t] << 2) + s];
                    }
                }
            }

            uint8_t* block = dst + (static_cast<size_t>(by) * blockColumns + bx) * blockBytes;

            switch (format)
            {
                case 0: D3DXEncodeBC1(block, texels, bc1_alpha_threshold, flags); break;
                case 1: D3DXEncodeBC4U(block, texels, flags); break;
                case 2: D3DXEncodeBC5U(block, texels, flags); break;
                default: D3DXEncodeBC7(block, texels, flags); break;
            }
        }
    }
}

} // extern "C"
SOURCE

    step "Compiling libdxtexshim.so"
    (
        cd "$OUT_DIR"
        g++ -std=c++17 -O3 -DNDEBUG -fPIC -shared \
            -I"$DIRECTXTEX_DIR/DirectXTex" \
            -I"$CHECKOUT_DIR/unix_external/DirectXMath/Inc" \
            -I"$CHECKOUT_DIR/unix_external/sal" \
            "$SHIM_SRC" "$STATIC_LIB" \
            -o "$OUT_LIB"
    )
fi

# ------------------------------------------------------------------- verification
step "Verifying exports"
for symbol in dxtex_block_bytes dxtex_decode dxtex_encode; do
    nm -D --defined-only "$OUT_LIB" | grep -q " T $symbol$" ||
        die "missing export $symbol in $OUT_LIB"
    info "export OK: $symbol"
done

[ -s "$OUT_LIB" ] || die "shim is empty: $OUT_LIB"

step "Done"
info "$OUT_LIB"
printf '\n%s\n' "$OUT_LIB"
